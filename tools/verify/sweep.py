#!/usr/bin/env python3
"""Generate the verification script for tia_dump.

Writes <out>.txt (register-write script) and <out>.csv (one row per
single-voice segment, for check_periods.py).

Parts:
  1. every AUDC x AUDF with voice 0 alone (AUDV0 = 15, AUDV1 = 0)
  2. the same with voice 1 alone
  3. every AUDV value on both voices, for a few modes
  4. random writes to both voices at random times (fixed seed)
"""

import csv
import random
import sys

import tia_model

SETTLE = 256  # ticks skipped at the start of each segment before checking


def main():
    if len(sys.argv) != 2:
        sys.exit("usage: sweep.py <out-prefix>")
    prefix = sys.argv[1]

    lines = []
    segments = []
    tick = 0

    def write(reg, value):
        lines.append(f"{tick} {reg} {value}")

    # 1 and 2: each voice alone, every AUDC x AUDF
    for voice, other in ((0, 1), (1, 0)):
        write(f"AUDV{other}", 0)
        write(f"AUDV{voice}", 15)
        for audc in range(16):
            for audf in range(32):
                write(f"AUDC{voice}", audc)
                write(f"AUDF{voice}", audf)
                length = max(1024, SETTLE + 3 * tia_model.expected_period(audc, audf))
                segments.append((tick, length, voice, audc, audf, 15))
                tick += length
        write(f"AUDV{voice}", 0)

    # 3: every volume, both voices, a few modes
    for audc, audf in ((4, 0), (1, 5), (8, 2), (12, 7)):
        write("AUDC0", audc)
        write("AUDF0", audf)
        write("AUDC1", audc)
        write("AUDF1", audf + 3)
        for v0 in range(16):
            write("AUDV0", v0)
            write("AUDV1", 15 - v0)
            tick += 500

    # 4: random writes, both voices
    rng = random.Random(2600)
    regs = ["AUDC0", "AUDC1", "AUDF0", "AUDF1", "AUDV0", "AUDV1"]
    for _ in range(5000):
        reg = rng.choice(regs)
        value = rng.randrange(256)  # full byte: unused bits must be ignored
        write(reg, value)
        tick += rng.choice((0, 1, 2, 3, 7, 31, 100, 1000))

    lines.append(f"{tick} end")

    with open(prefix + ".txt", "w") as f:
        f.write("# generated by tools/verify/sweep.py\n")
        f.write("\n".join(lines) + "\n")
    with open(prefix + ".csv", "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["start", "length", "voice", "audc", "audf", "audv"])
        w.writerows(segments)
    print(f"{prefix}.txt: {tick} ticks, {len(segments)} single-voice segments")


if __name__ == "__main__":
    main()
